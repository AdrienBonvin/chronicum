const STRINGS: Record<Lang, Record<StringKey, string>> = { en: EN, fr: FR };

let lang: Lang = "en";

export function setLang(next: Lang): void {
  lang = next;
}

export function getLang(): Lang {
  return lang;
}

/** The name `{who}` stands for, player `n`'s: the app gives it their army once picked */
let nameOf = (n: number): string => t("playerNumber", { n });

export function setPlayerNames(names: (n: number) => string): void {
  nameOf = names;
}

/** `{name}` placeholders are filled from `vars`; `{who}` is the name of player `n` */
export function t(key: StringKey, vars: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name === "who" && "n" in vars ? nameOf(Number(vars.n)) : name in vars ? String(vars[name]) : match,
  );
}
